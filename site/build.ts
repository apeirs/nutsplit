// Builds the static demo site in site/ (GitHub Pages):
//   site/split.js  - src/split.ts with its types stripped: the same split code the server runs
//   site/feed.json - the Nodesignal feed snapshot from test/fixtures, parsed by src/feed.ts
// The ledger pages in site/demo/ are copied from a real `node demo/run.ts` / `node demo/nutzap.ts`
// run with `node site/build.ts --ledgers` (they need network to the test mints, so CI does not rerun them).
import { gunzipSync } from 'node:zlib';
import { copyFileSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import ts from 'typescript';
import { parseFeed } from '../src/feed.ts';

const root = new URL('../', import.meta.url);
const at = (p: string) => new URL(p, root);

const src = readFileSync(at('src/split.ts'), 'utf8');
const js = ts.transpileModule(src, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, rewriteRelativeImportExtensions: true },
}).outputText;
writeFileSync(at('site/split.js'), `// Generated by site/build.ts from src/split.ts. Do not edit.\n${js}`);

const feed = parseFeed(gunzipSync(readFileSync(at('test/fixtures/nodesignal-feed.xml.gz'))).toString('utf8'));
const slim = {
  title: feed.title,
  podcastGuid: feed.podcastGuid,
  snapshot: '2026-11-07',
  value: feed.value,
  items: feed.items.map(({ guid, title, value }) => ({ guid, title, value })),
};
writeFileSync(at('site/feed.json'), JSON.stringify(slim));

if (process.argv.includes('--ledgers')) {
  const copies: Array<[string, string]> = [
    ['demo/out/ledger.html', 'site/demo/ledger.html'],
    ['demo/out/ledger.json', 'site/demo/ledger.json'],
    ['demo/out/nutzap/ledger.html', 'site/demo/nutzap-ledger.html'],
    ['demo/out/nutzap/ledger.json', 'site/demo/nutzap-ledger.json'],
  ];
  for (const [from, to] of copies) {
    if (!existsSync(at(from))) throw new Error(`${from} missing: run the demos first`);
    copyFileSync(at(from), at(to));
  }
  // The live server answers ?format=json; the static copy links the JSON file next to it.
  for (const [page, json] of [['site/demo/ledger.html', 'ledger.json'], ['site/demo/nutzap-ledger.html', 'nutzap-ledger.json']]) {
    writeFileSync(at(page), readFileSync(at(page), 'utf8').replaceAll('href="?format=json"', `href="${json}"`));
  }
}
console.log(`site/split.js, site/feed.json (${feed.items.length} items)${process.argv.includes('--ledgers') ? ', site/demo/*' : ''}`);
